import { access, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const serverManifest = await import(
  path.join(repoRoot, "functions/lib/policy/youthWrestlingPlacementManifest.js")
);
const { WRESTLING_CARD_FAMILIES } = await import(
  pathToFileURL(path.join(repoRoot, "public/coaches/cards/wrestling/family-map.js"))
);

const CROSSWALK_VERSION = "r2c-youth-wrestling-tier-waves-v1";
const RANK_NAMES = Object.freeze({
  T0: "Shadow",
  T1: "Prospect",
  T2: "Competitor",
  T3: "Contender",
  T4: "Champion",
  CHAMPION_EXTENDED_DEVELOPMENT: "Champion Extended Development",
});

const legacyWaveModels = {};
for (let index = 0; index <= 7; index += 1) {
  const tier = `T${index}`;
  const sourcePath = path.join(
    repoRoot,
    `public/assets/js/hybrid/youth/youth-zero-to-hero-wrestling-t${index}-waves.js`
  );
  legacyWaveModels[tier] = await import(pathToFileURL(sourcePath));
}

function cardSlug(originalCardPath) {
  return path.basename(originalCardPath, ".html").replace(/^skill-\d+-/, "");
}

function legacyPlacement(entry) {
  const slug = cardSlug(entry.originalCardPath);
  const model = legacyWaveModels[entry.originalCurriculumTier];
  const matchingWaves = Object.entries(model?.SKILL_WAVES || {})
    .filter(([, slugs]) => Array.isArray(slugs) && slugs.includes(slug))
    .map(([wave]) => wave);
  const isFoundation = Array.isArray(model?.FOUNDATIONS) && model.FOUNDATIONS.includes(slug);
  if (matchingWaves.length + Number(isFoundation) !== 1) {
    throw new Error(
      `${entry.cardId} must resolve to exactly one legacy Wrestling foundation or wave; ` +
      `found ${matchingWaves.length + Number(isFoundation)}`
    );
  }
  return { slug, wave: matchingWaves[0] || "", isFoundation };
}

function browserCard(entry, legacy) {
  return Object.freeze({
    id: entry.cardId,
    cardId: entry.cardId,
    title: entry.skillTitle,
    href: `/${entry.originalCardPath.replace(/^public\//, "")}`,
    journey: "r2c",
    discipline: "wrestling",
    tier: entry.placement.toLowerCase(),
    originalTier: entry.originalCurriculumTier.toLowerCase(),
    familyId: entry.familyMappingStatus === "AUTHORITATIVE_EXISTING" ? entry.familyId : "",
    manifestFamilyId: entry.familyId,
    familyMappingStatus: entry.familyMappingStatus,
    curriculumStatus: entry.curriculumStatus,
    legacySkillSlug: legacy.slug,
    legacyWave: legacy.wave || "foundation",
    progressionVerified: false,
  });
}

const projection = {
  version: serverManifest.R2C_YOUTH_WRESTLING_PLACEMENT_VERSION,
  approvedCounts: serverManifest.R2C_YOUTH_WRESTLING_APPROVED_COUNTS,
  placements: serverManifest.R2C_YOUTH_WRESTLING_PLACEMENTS.map((entry) => ({
    cardId: entry.cardId,
    originalCardPath: entry.originalCardPath,
    originalCurriculumTier: entry.originalCurriculumTier,
    placement: entry.placement,
    skillTitle: entry.skillTitle,
    familyId: entry.familyId,
    familyMappingStatus: entry.familyMappingStatus,
    curriculumStatus: entry.curriculumStatus,
  })),
};

const outputPath = path.join(
  repoRoot,
  "public/assets/data/youth-wrestling-placement-manifest.json"
);

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, `${JSON.stringify(projection, null, 2)}\n`, "utf8");
console.log(`Wrote ${projection.placements.length} placements to ${outputPath}`);

const crosswalkTiers = Object.fromEntries(
  Object.keys(RANK_NAMES).map((tier) => [tier, {
    rankName: RANK_NAMES[tier],
    foundations: [],
    waves: {},
  }])
);

for (const entry of serverManifest.R2C_YOUTH_WRESTLING_PLACEMENTS) {
  await access(path.join(repoRoot, entry.originalCardPath));
  const legacy = legacyPlacement(entry);
  const card = browserCard(entry, legacy);
  const authoritativeFamily = WRESTLING_CARD_FAMILIES.r2c?.[
    entry.originalCurriculumTier.toLowerCase()
  ]?.[legacy.slug];
  if (
    entry.familyMappingStatus === "AUTHORITATIVE_EXISTING" &&
    authoritativeFamily !== entry.familyId
  ) {
    throw new Error(
      `${entry.cardId} family drift: manifest=${entry.familyId}, existing=${authoritativeFamily || "missing"}`
    );
  }
  const destination = crosswalkTiers[entry.placement];
  if (!destination) throw new Error(`Unsupported placement ${entry.placement}`);
  if (legacy.isFoundation) {
    destination.foundations.push(card);
  } else {
    (destination.waves[legacy.wave] ||= []).push(card);
  }
}

const crosswalk = {
  version: CROSSWALK_VERSION,
  placementVersion: serverManifest.R2C_YOUTH_WRESTLING_PLACEMENT_VERSION,
  journey: "road2champion",
  discipline: "wrestling",
  evidenceEffect: "none",
  tiers: crosswalkTiers,
};
const crosswalkPath = path.join(
  repoRoot,
  "public/assets/js/hybrid/youth/road2champion-wrestling-tier-wave-crosswalk.js"
);
const crosswalkSource = [
  "// Generated by scripts/generate-youth-wrestling-browser-manifest.mjs. Do not edit by hand.",
  `export const R2C_YOUTH_WRESTLING_TIER_WAVE_CROSSWALK = Object.freeze(${JSON.stringify(crosswalk, null, 2)});`,
  "",
].join("\n");
await writeFile(crosswalkPath, crosswalkSource, "utf8");
console.log(`Wrote ${CROSSWALK_VERSION} to ${crosswalkPath}`);
