const clean = value => String(value ?? "").trim();

export function generalMessagePayload(fields, serverTimestamp, source = "public-message-page") {
  return {
    organization: "sandman-system",
    pipeline: "general-messaging",
    source,
    status: "NEW",
    messageStatus: "NEW",
    contactName: clean(fields.contactName),
    email: clean(fields.email).toLowerCase(),
    phone: clean(fields.phone),
    topic: clean(fields.topic),
    passType: clean(fields.passType),
    message: clean(fields.message),
    contactConsent: fields.contactConsent === true,
    language: fields.language,
    pagePath: fields.pagePath,
    routingStage: "ADMIN_REVIEW",
    nextRoutingStage: "MANAGEMENT_TRIAGE",
    routingPolicy: "ADMIN_TO_ORGANIZATION_LOCATION_MANAGER",
    requiredManagerLevel: "LOCATION_MANAGER",
    assignmentStatus: "UNASSIGNED",
    preferredOrganization: "not-sure",
    preferredLocation: "not-sure",
    organizationId: null,
    organizationName: "",
    academyId: null,
    academyName: "",
    locationId: null,
    locationName: "",
    assignedAdminUid: null,
    assignedManagerUid: null,
    assignedCoachUid: null,
    respondedByUid: null,
    respondedByRole: null,
    respondedAt: null,
    closedByUid: null,
    closedAt: null,
    escalated: false,
    escalationReason: "",
    coachNotes: "",
    managementNotes: "",
    createdAt: serverTimestamp(),
    updatedAt: serverTimestamp()
  };
}
