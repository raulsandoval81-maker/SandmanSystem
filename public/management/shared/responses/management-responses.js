export function getManagementResponseFamily(topic) {
  const key = String(topic || "")
    .trim()
    .toLowerCase();

  return (
    MANAGEMENT_RESPONSE_FAMILIES[key] ||
    MANAGEMENT_RESPONSE_FAMILIES.other
  );
}


export function getManagementResponse(
  topic,
  templateId = ""
) {
  const family =
    getManagementResponseFamily(topic);

  const selected =
    family.templates.find(
      (template) =>
        template.id === templateId
    ) ||
    family.templates[0];

  return {
    familyLabel: family.label,
    ...selected
  };
}
